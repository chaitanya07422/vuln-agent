from __future__ import annotations

import html
from typing import Any, Dict, List


def render_scan_html(scan: Dict[str, Any], *, branded: bool = True) -> str:
    url = html.escape(str(scan.get("url") or ""))
    summary = scan.get("summary") or {}
    headline = html.escape(str(summary.get("headline") or "Scan complete"))
    verdict = html.escape(str(summary.get("verdict") or scan.get("status") or ""))
    watermark = "" if branded else '<p class="wm">ScanLead Free — upgrade for branded PDF</p>'
    agents_html = ""
    for row in summary.get("agents") or []:
        status = html.escape(str(row.get("status") or ""))
        label = html.escape(str(row.get("label") or row.get("agent") or ""))
        note = html.escape(str(row.get("note") or ""))
        agents_html += f"<tr><td>{status}</td><td>{label}</td><td>{note}</td></tr>"

    findings = [
        f
        for f in (scan.get("findings") or [])
        if f.get("severity") in ("critical", "high", "medium", "low")
        and f.get("agent") != "reporter"
    ]
    findings_html = ""
    for f in findings:
        findings_html += (
            f"<article class='finding'>"
            f"<h3>[{html.escape(str(f.get('severity', '')).upper())}] {html.escape(str(f.get('title') or ''))}</h3>"
            f"<p class='meta'>{html.escape(str(f.get('agent') or ''))}</p>"
            f"<p>{html.escape(str(f.get('explanation') or f.get('evidence_snippet') or ''))}</p>"
            f"<p><strong>Fix:</strong> {html.escape(str(f.get('fix') or '—'))}</p>"
            f"</article>"
        )
    if not findings_html:
        findings_html = "<p>No priority findings.</p>"

    risk = html.escape(str(scan.get("risk_path") or "")).replace("\n", "<br/>")
    risk_block = f"<h2>How this could be abused</h2><p>{risk}</p>" if scan.get("risk_path") else ""

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<title>ScanLead brief — {url}</title>
<style>
  body {{ font-family: Georgia, serif; color: #13201a; max-width: 820px; margin: 40px auto; padding: 0 20px; line-height: 1.5; }}
  h1 {{ font-size: 2rem; margin-bottom: 0.2rem; }}
  .muted {{ color: #5c6f66; }}
  .wm {{ color: #9a6b1f; font-size: 0.9rem; }}
  table {{ width: 100%; border-collapse: collapse; margin: 1rem 0 2rem; }}
  td, th {{ border-top: 1px solid #d5e0da; padding: 0.55rem 0.4rem; text-align: left; font-size: 0.95rem; }}
  .finding {{ border: 1px solid #d5e0da; border-radius: 10px; padding: 1rem; margin: 0.8rem 0; }}
  .meta {{ font-family: ui-monospace, monospace; font-size: 0.8rem; color: #5c6f66; }}
  @media print {{ body {{ margin: 0; }} .no-print {{ display: none; }} }}
</style>
</head>
<body>
  <p class="muted no-print"><button onclick="window.print()">Print / Save as PDF</button></p>
  {watermark}
  <h1>Security brief</h1>
  <p class="muted">{url}</p>
  <p><strong>{verdict}</strong> — {headline}</p>
  <h2>What we checked</h2>
  <table><thead><tr><th>Status</th><th>Check</th><th>Note</th></tr></thead>
  <tbody>{agents_html or "<tr><td colspan=3>No agent summary</td></tr>"}</tbody></table>
  {risk_block}
  <h2>Findings</h2>
  {findings_html}
  <p class="muted">Generated by ScanLead · detect-only authorized scan</p>
</body>
</html>"""
